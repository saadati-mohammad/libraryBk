CREATE TABLE input_device (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    type_key VARCHAR(64) NOT NULL,
    owner_username VARCHAR(80),
    station VARCHAR(120),
    config_json CLOB NOT NULL,
    capabilities_json CLOB NOT NULL,
    token_hash VARCHAR(64) UNIQUE,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    revoked_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    last_seen_at TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0
);

CREATE INDEX idx_input_device_type_enabled ON input_device(type_key, enabled);
CREATE INDEX idx_input_device_owner ON input_device(owner_username);

CREATE TABLE input_device_audit_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id BIGINT NOT NULL,
    actor_username VARCHAR(80) NOT NULL,
    action VARCHAR(32) NOT NULL,
    details_json CLOB NOT NULL,
    remote_address VARCHAR(64),
    occurred_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_input_device_audit_device FOREIGN KEY (device_id) REFERENCES input_device(id)
);

CREATE INDEX idx_input_device_audit_device_time ON input_device_audit_event(device_id, occurred_at);
